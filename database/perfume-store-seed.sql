-- Insert application records in foreign-key order.
START TRANSACTION;

-- 1. Categories and products. IDs are looked up rather than assumed to start at 1.
INSERT INTO categories (name, description)
SELECT s.name, s.description
FROM ps_seed_categories s
LEFT JOIN categories existing ON existing.name = s.name
WHERE existing.id IS NULL;

INSERT INTO ps_seed_category_map (seed_id, real_id)
SELECT s.seed_id, MIN(c.id)
FROM ps_seed_categories s JOIN categories c ON c.name = s.name
GROUP BY s.seed_id;

INSERT INTO products (name, brand, description, price, stock_quantity, size_ml, concentration, active, version)
SELECT s.name, s.brand, s.description, s.price, s.stock_quantity, s.size_ml, s.concentration, s.active, 0
FROM ps_seed_products s
LEFT JOIN products existing ON existing.name = s.name AND existing.brand = s.brand AND existing.size_ml = s.size_ml
WHERE existing.id IS NULL;

INSERT INTO ps_seed_product_map (seed_id, real_id)
SELECT s.seed_id, MIN(p.id)
FROM ps_seed_products s
JOIN products p ON p.name = s.name AND p.brand = s.brand AND p.size_ml = s.size_ml
GROUP BY s.seed_id;

-- 2. Many-to-many category links. Every sample perfume has multiple categories.
INSERT INTO product_categories (product_id, category_id)
SELECT pm.real_id, cm.real_id
FROM ps_seed_links s
JOIN ps_seed_product_map pm ON pm.seed_id = s.product_seed_id
JOIN ps_seed_category_map cm ON cm.seed_id = s.category_seed_id
LEFT JOIN product_categories existing ON existing.product_id = pm.real_id AND existing.category_id = cm.real_id
WHERE existing.product_id IS NULL;

-- 3. Accounts. BCrypt values already contain the {bcrypt} prefix.
INSERT INTO users (name, email, password_hash, role)
SELECT s.name, s.email, s.password_hash, s.role
FROM ps_seed_users s
LEFT JOIN users existing ON existing.email = s.email
WHERE existing.id IS NULL;

INSERT INTO ps_seed_user_map (seed_id, real_id)
SELECT s.seed_id, u.id
FROM ps_seed_users s JOIN users u ON u.email = s.email;

-- 4. One cart for each sample customer. The last five start empty.
INSERT INTO carts (user_id)
SELECT um.real_id
FROM ps_seed_user_map um
LEFT JOIN carts existing ON existing.user_id = um.real_id
WHERE um.seed_id > 0 AND existing.id IS NULL;

INSERT INTO ps_seed_cart_map (user_seed_id, real_id)
SELECT um.seed_id, c.id
FROM ps_seed_user_map um JOIN carts c ON c.user_id = um.real_id
WHERE um.seed_id > 0;

INSERT INTO cart_items (cart_id, product_id, quantity)
SELECT cm.real_id, pm.real_id, s.quantity
FROM ps_seed_cart_items s
JOIN ps_seed_cart_map cm ON cm.user_seed_id = s.user_seed_id
JOIN ps_seed_product_map pm ON pm.seed_id = s.product_seed_id
LEFT JOIN cart_items existing ON existing.cart_id = cm.real_id AND existing.product_id = pm.real_id
WHERE existing.id IS NULL;

-- 5. Historical orders. Snapshot prices can differ from current catalog prices.
INSERT INTO orders (user_id, created_at, total_amount)
SELECT um.real_id, s.created_at, s.total_amount
FROM ps_seed_orders s
JOIN ps_seed_user_map um ON um.seed_id = s.user_seed_id
LEFT JOIN orders existing ON existing.user_id = um.real_id AND existing.created_at = s.created_at
WHERE existing.id IS NULL;

INSERT INTO ps_seed_order_map (seed_id, real_id)
SELECT s.seed_id, MIN(o.id)
FROM ps_seed_orders s
JOIN ps_seed_user_map um ON um.seed_id = s.user_seed_id
JOIN orders o ON o.user_id = um.real_id AND o.created_at = s.created_at
GROUP BY s.seed_id;

INSERT INTO order_items (order_id, product_id, product_name, unit_price, quantity)
SELECT om.real_id, pm.real_id, s.product_name, s.unit_price, s.quantity
FROM ps_seed_order_items s
JOIN ps_seed_order_map om ON om.seed_id = s.order_seed_id
JOIN ps_seed_product_map pm ON pm.seed_id = s.product_seed_id
LEFT JOIN order_items existing ON existing.order_id = om.real_id AND existing.product_id = pm.real_id
WHERE existing.id IS NULL;

-- 6. Reviews, at most one per customer/product pair.
INSERT INTO reviews (user_id, product_id, rating, comment, created_at)
SELECT um.real_id, pm.real_id, s.rating, s.comment, s.created_at
FROM ps_seed_reviews s
JOIN ps_seed_user_map um ON um.seed_id = s.user_seed_id
JOIN ps_seed_product_map pm ON pm.seed_id = s.product_seed_id
LEFT JOIN reviews existing ON existing.user_id = um.real_id AND existing.product_id = pm.real_id
WHERE existing.id IS NULL;

